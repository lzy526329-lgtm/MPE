import { build } from 'esbuild';
import { resolve } from 'node:path';
// Generated standalone runtime includes the exact same level and Rapier physics as the client.
const outfile = resolve(process.argv[2] || '../gognju-server/server/game/cloudPawsRuntime.cjs');
await build({ entryPoints: ['games/cloud-paws/server/rooms.js'], outfile, bundle: true, platform: 'node', format: 'cjs', target: 'node20', minify: true,
  banner: { js: '// GENERATED by gognju/scripts/build-cloud-paws-server.mjs. Edit the source in gognju/games/cloud-paws, then rebuild.' } });
console.log(`Cloud Paws server runtime: ${outfile}`);
